import { SQL } from "bun";
import { mkdirSync } from "node:fs";
import { dirname } from "node:path";
import logger from "../client/logger.js";

/** Lo que se guarda de una canción: lo justo para mostrarla y volver a buscarla por su enlace */
export interface SavedTrack {
    uri: string;
    title: string;
    author: string;
    duration: number;
    artworkUrl?: string | null;
}

export interface FavoriteRow extends SavedTrack {
    addedAt: number;
}

export interface PlaylistSummary {
    id: number;
    name: string;
    trackCount: number;
}

export interface PlaylistTrackRow extends SavedTrack {
    position: number;
}

/**
 * A qué base conectarse:
 * - `DATABASE_URL` (postgres://...): una base compartida, por ejemplo Supabase, para que varias PCs con el bot vean los mismos datos.
 * - Si no está: el archivo SQLite de `DB_PATH` (por defecto data/bot.db), como antes. No hace falta configurar nada.
 */
export function databaseUrl(env = process.env): string {
    if (env.DATABASE_URL) return env.DATABASE_URL;
    const path = env.DB_PATH ?? "data/bot.db";
    return path === ":memory:" ? ":memory:" : `sqlite://${path}`;
}

/** Para los logs: el tipo de base y el host, nunca el usuario ni la contraseña */
function describe(url: string): string {
    if (!/^postgres(ql)?:\/\//.test(url)) return `SQLite (${url.replace(/^sqlite:\/\//, "")})`;
    try { return `Postgres (${new URL(url).hostname})`; } catch { return "Postgres"; }
}

/**
 * Bun no cifra la conexión a Postgres si no se le pide (sslmode=disable por defecto), y la contraseña viajaría
 * en claro por internet. Se pide TLS para cualquier base que no esté en esta máquina, salvo que la URL ya diga
 * su propio sslmode (por ejemplo ?sslmode=disable para un Postgres en la red de Docker).
 */
export function needsTls(url: string): boolean {
    if (!/^postgres(ql)?:\/\//.test(url) || /[?&]sslmode=/.test(url)) return false;
    try {
        return !["localhost", "127.0.0.1", "[::1]"].includes(new URL(url).hostname);
    } catch {
        return true;
    }
}

const toFavorite =(row: any): FavoriteRow => ({ ...row, addedAt: Number(row.addedAt) });

/**
 * Base de datos del bot: favoritos y playlists por usuario, y el volumen por servidor.
 * `Bun.SQL` viene con Bun y habla SQLite y Postgres con el mismo código: sin dependencias.
 *
 * Diferencias entre los dos que se cuidan acá:
 * - Postgres devuelve BIGINT y COUNT(*) como texto: los conteos se castean a INTEGER y `added_at` pasa por Number().
 * - Los alias en camelCase van entre comillas ("artworkUrl"): sin ellas Postgres los pasa a minúsculas.
 * - No hay COLLATE NOCASE en Postgres: los nombres de playlist se comparan con lower().
 */
export class BotDatabase {
    private sql: SQL;
    private postgres: boolean;
    /** Las tablas se crean al abrir; cada consulta espera a que estén */
    private ready: Promise<void>;

    constructor(url = databaseUrl()) {
        this.postgres = /^postgres(ql)?:\/\//.test(url);
        if (url.startsWith("sqlite://")) mkdirSync(dirname(url.slice("sqlite://".length)), { recursive: true });
        this.sql = new SQL(url, needsTls(url) ? { tls: true } : {});
        this.ready = this.migrate();
        // Si falla (contraseña mal, base pausada) el bot sigue: la música no depende de la base, y cada consulta vuelve a mostrar el error
        this.ready
            .then(() => logger.info(`[DB] Base lista: ${describe(url)}`))
            .catch(err => logger.error(`[DB] No se pudo abrir la base ${describe(url)}: ${(err as Error).message}`));
    }

    private async migrate() {
        if (!this.postgres) {
            // WAL + espera: varios shards (procesos) pueden usar el mismo archivo sin "database is locked"
            await this.sql.unsafe("PRAGMA journal_mode = WAL");
            await this.sql.unsafe("PRAGMA busy_timeout = 5000");
            await this.sql.unsafe("PRAGMA foreign_keys = ON");
        }
        // Lo único que cambia entre motores es el id autoincremental. INTEGER PRIMARY KEY es el rowid de SQLite
        const id = this.postgres ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT";

        // BIGINT para las fechas en ms (Date.now() no entra en un INTEGER de Postgres); en SQLite es lo mismo que INTEGER
        await this.sql.unsafe(`
            CREATE TABLE IF NOT EXISTS favorites (
                user_id     TEXT    NOT NULL,
                uri         TEXT    NOT NULL,
                title       TEXT    NOT NULL,
                author      TEXT    NOT NULL,
                duration    INTEGER NOT NULL,
                artwork_url TEXT,
                added_at    BIGINT  NOT NULL,
                PRIMARY KEY (user_id, uri)
            )`);
        await this.sql.unsafe(`
            CREATE TABLE IF NOT EXISTS playlists (
                id         ${id},
                user_id    TEXT    NOT NULL,
                name       TEXT    NOT NULL,
                created_at BIGINT  NOT NULL,
                UNIQUE (user_id, name)
            )`);
        await this.sql.unsafe(`
            CREATE TABLE IF NOT EXISTS playlist_tracks (
                playlist_id INTEGER NOT NULL REFERENCES playlists(id) ON DELETE CASCADE,
                position    INTEGER NOT NULL,
                uri         TEXT    NOT NULL,
                title       TEXT    NOT NULL,
                author      TEXT    NOT NULL,
                duration    INTEGER NOT NULL,
                artwork_url TEXT,
                PRIMARY KEY (playlist_id, position)
            )`);
        // Ajustes por servidor: el volumen con el que arranca el reproductor (/volume default) y el idioma (/language)
        await this.sql.unsafe(`
            CREATE TABLE IF NOT EXISTS guild_settings (
                guild_id TEXT PRIMARY KEY,
                volume   INTEGER,
                language TEXT
            )`);
        await this.addColumn("guild_settings", "language", "TEXT");
    }

    /** Agrega una columna a una tabla creada por una versión anterior. No falla si ya existe */
    private async addColumn(table: string, column: string, type: string) {
        if (this.postgres) {
            await this.sql.unsafe(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${column} ${type}`);
            return;
        }
        // SQLite no tiene IF NOT EXISTS para columnas
        const columns: { name: string }[] = await this.sql.unsafe(`PRAGMA table_info(${table})`);
        if (columns.some(c => c.name === column)) return;
        try {
            await this.sql.unsafe(`ALTER TABLE ${table} ADD COLUMN ${column} ${type}`);
            logger.info(`[DB] Columna nueva: ${table}.${column}`);
        } catch (err) {
            // Otro shard la agregó entre la consulta y el ALTER
            if (!/duplicate column/i.test((err as Error).message)) throw err;
        }
    }

    /** La conexión, después de crear las tablas */
    private async db() {
        await this.ready;
        return this.sql;
    }

    /** Volumen por defecto del servidor. `null` si nunca se eligió uno */
    async getGuildVolume(guildId: string): Promise<number | null> {
        const sql = await this.db();
        const [row] = await sql`SELECT volume FROM guild_settings WHERE guild_id = ${guildId}`;
        return row?.volume ?? null;
    }

    async setGuildVolume(guildId: string, volume: number) {
        const sql = await this.db();
        await sql`
            INSERT INTO guild_settings (guild_id, volume) VALUES (${guildId}, ${volume})
            ON CONFLICT (guild_id) DO UPDATE SET volume = excluded.volume`;
    }

    /** Idioma elegido con /language ("es", "en"). `null` si nunca se eligió: se usa el de Discord */
    async getGuildLanguage(guildId: string): Promise<string | null> {
        const sql = await this.db();
        const [row] = await sql`SELECT language FROM guild_settings WHERE guild_id = ${guildId}`;
        return row?.language ?? null;
    }

    async setGuildLanguage(guildId: string, language: string) {
        const sql = await this.db();
        await sql`
            INSERT INTO guild_settings (guild_id, language) VALUES (${guildId}, ${language})
            ON CONFLICT (guild_id) DO UPDATE SET language = excluded.language`;
    }

    /** Agrega la canción a los favoritos del usuario, o la quita si ya estaba (botón ❤️) */
    async toggleFavorite(userId: string, track: SavedTrack): Promise<"added" | "removed"> {
        const sql = await this.db();
        return sql.begin(async tx => {
            const removed = await tx`DELETE FROM favorites WHERE user_id = ${userId} AND uri = ${track.uri}`;
            if (removed.count > 0) return "removed" as const;
            await this.insertFavorite(tx, userId, track);
            return "added" as const;
        });
    }

    /** Agrega la canción a los favoritos del usuario. `false` si ya estaba (no la duplica ni la quita) */
    async addFavorite(userId: string, track: SavedTrack): Promise<boolean> {
        return (await this.insertFavorite(await this.db(), userId, track)).count > 0;
    }

    private insertFavorite(sql: SQL, userId: string, track: SavedTrack, addedAt = Date.now()) {
        return sql`
            INSERT INTO favorites (user_id, uri, title, author, duration, artwork_url, added_at)
            VALUES (${userId}, ${track.uri}, ${track.title}, ${track.author}, ${track.duration}, ${track.artworkUrl ?? null}, ${addedAt})
            ON CONFLICT DO NOTHING`;
    }

    /** Quita una canción de los favoritos del usuario. `false` si no estaba */
    async removeFavorite(userId: string, uri: string): Promise<boolean> {
        const sql = await this.db();
        return (await sql`DELETE FROM favorites WHERE user_id = ${userId} AND uri = ${uri}`).count > 0;
    }

    /** Favoritos del usuario, del más nuevo al más viejo */
    async getFavorites(userId: string): Promise<FavoriteRow[]> {
        const sql = await this.db();
        const rows = await sql`
            SELECT uri, title, author, duration, artwork_url AS "artworkUrl", added_at AS "addedAt"
            FROM favorites WHERE user_id = ${userId} ORDER BY added_at DESC`;
        return rows.map(toFavorite);
    }

    // ---------- Playlists: el nombre es único por usuario sin distinguir mayúsculas ----------

    /** Crea una playlist vacía. `null` si el usuario ya tiene una con ese nombre */
    async createPlaylist(userId: string, name: string): Promise<PlaylistSummary | null> {
        if (await this.getPlaylist(userId, name)) return null;
        const sql = await this.db();
        const [row] = await sql`INSERT INTO playlists (user_id, name, created_at) VALUES (${userId}, ${name}, ${Date.now()}) RETURNING id`;
        return { id: Number(row.id), name, trackCount: 0 };
    }

    /** Playlists del usuario ordenadas por nombre, con cuántas canciones tiene cada una */
    async getPlaylists(userId: string): Promise<PlaylistSummary[]> {
        const sql = await this.db();
        return [...await sql`
            SELECT p.id, p.name, (SELECT CAST(COUNT(*) AS INTEGER) FROM playlist_tracks t WHERE t.playlist_id = p.id) AS "trackCount"
            FROM playlists p WHERE p.user_id = ${userId} ORDER BY lower(p.name)`];
    }

    /** Playlist del usuario por nombre. Solo encuentra las propias */
    async getPlaylist(userId: string, name: string): Promise<PlaylistSummary | null> {
        const sql = await this.db();
        const [row] = await sql`
            SELECT p.id, p.name, (SELECT CAST(COUNT(*) AS INTEGER) FROM playlist_tracks t WHERE t.playlist_id = p.id) AS "trackCount"
            FROM playlists p WHERE p.user_id = ${userId} AND lower(p.name) = lower(${name})`;
        return row ?? null;
    }

    /** `false` si el nombre nuevo ya lo usa otra playlist del usuario */
    async renamePlaylist(userId: string, playlistId: number, newName: string): Promise<boolean> {
        const other = await this.getPlaylist(userId, newName);
        if (other && other.id !== playlistId) return false;
        const sql = await this.db();
        return (await sql`UPDATE playlists SET name = ${newName} WHERE id = ${playlistId} AND user_id = ${userId}`).count > 0;
    }

    /** Borra la playlist y sus canciones */
    async deletePlaylist(userId: string, playlistId: number): Promise<boolean> {
        const sql = await this.db();
        return (await sql`DELETE FROM playlists WHERE id = ${playlistId} AND user_id = ${userId}`).count > 0;
    }

    /** Agrega la canción al final. `false` si ya estaba en esa playlist */
    async addToPlaylist(playlistId: number, track: SavedTrack): Promise<boolean> {
        const sql = await this.db();
        return sql.begin(async tx => {
            const [exists] = await tx`SELECT 1 FROM playlist_tracks WHERE playlist_id = ${playlistId} AND uri = ${track.uri}`;
            if (exists) return false;

            await tx`
                INSERT INTO playlist_tracks (playlist_id, position, uri, title, author, duration, artwork_url)
                VALUES (${playlistId},
                        (SELECT COALESCE(MAX(position), 0) + 1 FROM playlist_tracks WHERE playlist_id = ${playlistId}),
                        ${track.uri}, ${track.title}, ${track.author}, ${track.duration}, ${track.artworkUrl ?? null})`;
            return true;
        });
    }

    /** Canciones de la playlist en el orden en que se agregaron */
    async getPlaylistTracks(playlistId: number): Promise<PlaylistTrackRow[]> {
        const sql = await this.db();
        return [...await sql`
            SELECT position, uri, title, author, duration, artwork_url AS "artworkUrl"
            FROM playlist_tracks WHERE playlist_id = ${playlistId} ORDER BY position`];
    }

    /** Quita una canción por su posición (las demás no se renumeran: solo importa el orden) */
    async removeFromPlaylist(playlistId: number, position: number): Promise<boolean> {
        const sql = await this.db();
        return (await sql`DELETE FROM playlist_tracks WHERE playlist_id = ${playlistId} AND position = ${position}`).count > 0;
    }

    /** Solo para el script de migración: guarda un favorito con su fecha original */
    async importFavorite(userId: string, track: SavedTrack, addedAt: number): Promise<boolean> {
        return (await this.insertFavorite(await this.db(), userId, track, addedAt)).count > 0;
    }

    async close() {
        await this.ready.catch(() => { });
        await this.sql.close();
    }
}
